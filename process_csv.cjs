  // Simple regex to handle commas inside quotes
  const parts = line.match(/(".*?"|[^",\r\n]+)(?=\s*,|\s*$)/g);
  if (!parts || parts.length < 4) return;
  const vehicle = parts[0].trim().replace(/^"|"$/g, '');
  const from = parts[1].trim().replace(/^"|"$/g, '');
  const to = parts[2].trim().replace(/^"|"$/g, '');
